section_name = {sid: name for sid, name in SECTIONS}

# Number questions within each section -> id "S.NN"
counter = {}
questions = []
for sec, text, options, correct, ref in Q:
    assert correct in options, f"correct answer not in options: {text!r}"
    assert len(options) == len(set(options)), f"duplicate option in: {text!r}"
    counter[sec] = counter.get(sec, 0) + 1
    qid = f"{sec}.{counter[sec]:02d}"
    questions.append({
        "id": qid,
        "section": sec,
        "sectionName": section_name[sec],
        "question": text,
        "options": options,
        "answer": options.index(correct) + 1,  # 1-based
        "reference": ref,
    })

data = {
    "title": "ROC-A — Aeronautical Radio Operator Study Guide",
    "source": "Based on ISED RIC-21, Issue 3 (Feb 2010) — Study Guide for the Restricted Operator Certificate (Aeronautical)",
    "sections": [{"id": sid, "name": name} for sid, name in SECTIONS],
    "questions": questions,
}

out = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "assets", "data", "roca.json"))
with open(out, "w") as f:
    json.dump(data, f, indent=2, ensure_ascii=False)
    f.write("\n")

print(f"Wrote {len(questions)} questions / {len(SECTIONS)} sections -> {out}")
per = {}
for q in questions:
    per[q["section"]] = per.get(q["section"], 0) + 1
for sid, name in SECTIONS:
    print(f"  {sid:2d}. {name}: {per.get(sid, 0)}")
