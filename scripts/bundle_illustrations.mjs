#!/usr/bin/env node
// Bundles assets/illustrations/*.svg into src/illustrations/svg.generated.ts
// so the React Native app can render them with react-native-svg's SvgXml on
// iOS, Android and web without a custom Metro transformer. The manifest itself
// is imported as JSON at runtime; only the SVG markup needs this step.
//
//   node scripts/bundle_illustrations.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'assets', 'illustrations');
const manifest = JSON.parse(readFileSync(path.join(dir, 'manifest.json'), 'utf8'));

export function bundleSource() {
  const entries = [];
  const hash = createHash('sha1');
  for (const ill of manifest.illustrations) {
    let xml = readFileSync(path.join(dir, ill.file), 'utf8');
    // Keep the markup compact: the viewBox carries the size.
    xml = xml.replace(/<title>[\s\S]*?<\/title>\n?/, '').replace(/\n+/g, '\n').trim();
    const m = xml.match(/viewBox="0 0 (\d+) (\d+)"/);
    if (!m) throw new Error(`${ill.file}: missing viewBox`);
    hash.update(ill.id).update(xml);
    entries.push({ id: ill.id, w: Number(m[1]), h: Number(m[2]), xml });
  }
  const body = entries
    .map((e) => `  '${e.id}': { w: ${e.w}, h: ${e.h}, xml: ${JSON.stringify(e.xml)} },`)
    .join('\n');
  return (
    `// Generated by scripts/bundle_illustrations.mjs from assets/illustrations. Do not edit.\n` +
    `export const SVG_BUNDLE_HASH = '${hash.digest('hex')}';\n` +
    `export const SVG: Record<string, { w: number; h: number; xml: string }> = {\n${body}\n};\n`
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'src', 'illustrations', 'svg.generated.ts');
  writeFileSync(out, bundleSource());
  console.log(`wrote ${out}`);
}
